#!/usr/bin/env python3
"""Run all detection-layer configurations and publish BENCHMARK.md.

This script is the single source of truth for the public benchmark numbers.
It never invents results: if a layer is unavailable, it says so.

Usage:
    python benchmarks/run_and_publish.py
    python benchmarks/run_and_publish.py --corpus benchmarks/external_holdout.json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH_DIR = Path(__file__).resolve().parent

CONFIGS = [
    ("L1", {"AGENTGUARD_USE_ML": "false", "AGENTGUARD_USE_LLM_JUDGE": "false"}),
    ("L1+L2", {"AGENTGUARD_USE_ML": "true", "AGENTGUARD_USE_LLM_JUDGE": "false"}),
    ("L1+L2+L3", {"AGENTGUARD_USE_ML": "true", "AGENTGUARD_USE_LLM_JUDGE": "true"}),
]


def corpus_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def run_config(label: str, env_overrides: dict, corpus: Path) -> dict:
    """Run benchmark.py for one configuration and capture its JSON output."""
    env = os.environ.copy()
    env.update(env_overrides)
    out_json = BENCH_DIR / f".result_{label.replace('+', '_')}.json"

    cmd = [
        sys.executable,
        str(BENCH_DIR / "benchmark.py"),
        "--corpus",
        str(corpus),
        "--json-out",
        str(out_json),
    ]
    print(f"\n=== Running {label} ===")
    print(" ".join(cmd))
    proc = subprocess.run(cmd, env=env, capture_output=True, text=True)
    print(proc.stdout)
    if proc.returncode not in (0, 1):  # 1 = below threshold, still valid
        print(proc.stderr, file=sys.stderr)
        raise RuntimeError(f"benchmark.py failed for {label} (exit {proc.returncode})")

    if not out_json.exists():
        raise RuntimeError(
            f"benchmark.py did not produce {out_json}. "
            "Add a --json-out flag to benchmark.py that dumps the metrics dict."
        )
    return json.loads(out_json.read_text())


def render(results: dict, corpus: Path, chash: str) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Benchmark Results",
        "",
        f"> Generated by `benchmarks/run_and_publish.py` on {now}.",
        "> **Do not edit by hand.** Re-run the script to refresh.",
        "",
        "## Environment",
        "",
        f"- Python: {platform.python_version()}",
        f"- Platform: {platform.platform()}",
        f"- Corpus: `{corpus.name}` (sha256:{chash})",
        "",
        "## Results by configuration",
        "",
        "| Config | Recall | Precision | FPR | F1 | p50 (ms) | p95 (ms) | TP | FN | TN | FP |",
        "|--------|--------|-----------|-----|----|----------|----------|----|----|----|----|",
    ]
    for label, m in results.items():
        lines.append(
            "| {label} | {recall:.2%} | {precision:.2%} | {fpr:.2%} | {f1:.3f} | "
            "{p50:.1f} | {p95:.1f} | {tp} | {fn} | {tn} | {fp} |".format(
                label=label,
                recall=m.get("recall", 0.0),
                precision=m.get("precision", 0.0),
                fpr=m.get("fpr", 0.0),
                f1=m.get("f1", 0.0),
                p50=m.get("latency_p50_ms", m.get("latency_ms", 0.0)),
                p95=m.get("latency_p95_ms", 0.0),
                tp=m.get("tp", 0),
                fn=m.get("fn", 0),
                tn=m.get("tn", 0),
                fp=m.get("fp", 0),
            )
        )
    lines += [
        "",
        "## Reproduce",
        "",
        "```bash",
        "python benchmarks/run_and_publish.py",
        "```",
        "",
        "## Limitations",
        "",
        "See [`benchmarks/METHODOLOGY.md`](benchmarks/METHODOLOGY.md). Numbers on the",
        "internal corpus are an upper bound; the external holdout is reported separately.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--corpus",
        default=str(BENCH_DIR / "adversarial_corpus.json"),
        help="Path to the corpus JSON",
    )
    ap.add_argument("--out", default=str(ROOT / "BENCHMARK.md"))
    args = ap.parse_args()

    corpus = Path(args.corpus)
    if not corpus.exists():
        print(f"Corpus not found: {corpus}", file=sys.stderr)
        return 2

    chash = corpus_hash(corpus)
    results = {}
    for label, env in CONFIGS:
        try:
            results[label] = run_config(label, env, corpus)
        except RuntimeError as exc:
            print(f"[skip] {label}: {exc}", file=sys.stderr)

    if not results:
        print("No configuration produced results.", file=sys.stderr)
        return 1

    Path(args.out).write_text(render(results, corpus, chash))
    print(f"\nWrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
