"""Generate Markdown report from benchmark analysis."""
import json
from typing import Dict, Any
from datetime import datetime


def generate_markdown_report(analysis: Dict[str, Any], output_path: str):
    """Generate a Markdown report from benchmark analysis."""
    summary = analysis["summary"]
    categories = analysis["categories"]
    worst_cases = analysis.get("worst_cases", [])
    
    score = summary["overall_score"]
    if score >= 90:
        grade = "A (Excellent)"
        emoji = "🏆"
    elif score >= 80:
        grade = "B (Good)"
        emoji = "✅"
    elif score >= 70:
        grade = "C (Acceptable)"
        emoji = "⚠️"
    elif score >= 60:
        grade = "D (Needs Improvement)"
        emoji = "🟡"
    else:
        grade = "F (Critical)"
        emoji = "🚨"
    
    md = f"""# 🛡️ AgentGuard Adversarial Benchmark Report

**Generated**: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}  
**Overall Grade**: {emoji} **{grade}** ({score}/100)

---

## 📊 Summary

| Metric | Value |
|--------|-------|
| Total Prompts | {summary['total_prompts']} |
| Attack Prompts | {summary['attack_prompts']} |
| Benign Prompts | {summary['benign_prompts']} |
| **Detection Rate** | **{summary['detection_rate']}%** |
| **False Positive Rate** | **{summary['false_positive_rate']}%** |
| Precision | {summary['precision']}% |
| Recall | {summary['recall']}% |
| F1 Score | {summary['f1_score']}% |
| Avg Latency | {summary['avg_latency_ms']} ms |

### Confusion Matrix

|                | Predicted Attack | Predicted Benign |
|----------------|------------------|------------------|
| **Actual Attack** | TP: {summary['true_positives']} ✅ | FN: {summary['false_negatives']} ⚠️ |
| **Actual Benign** | FP: {summary['false_positives']} ⚠️ | TN: {summary['true_negatives']} ✅ |

---

## 📋 Category Breakdown

| Category | Total | Detected | Missed | Rate | Status |
|----------|-------|----------|--------|------|--------|
"""
    
    for cs in categories:
        if cs.detection_rate >= 0.9:
            status = "✅ Excellent"
        elif cs.detection_rate >= 0.7:
            status = "⚠️ Acceptable"
        else:
            status = "🚨 Critical"
        md += f"| {cs.category} | {cs.total} | {cs.detected} | {cs.missed} | {cs.detection_rate*100:.1f}% | {status} |\n"
    
    if worst_cases:
        md += f"""
---

## 🚨 Worst Missed Attacks (Top 10)

These are attack prompts that **were NOT detected** and require attention:

"""
        for i, case in enumerate(worst_cases[:10], 1):
            md += f"""### {i}. [{case['severity'].upper()}] {case['category']}

> {case['prompt']}

- **Severity**: {case['severity']}
- **Risk Level**: {case['risk_level']}

"""
    
    md += f"""
---

## 🎯 Recommendations

"""
    
    # Recommendations based on score
    if score < 70:
        md += """### 🔴 Critical Issues

1. **Low detection rate** - Consider adding more regex patterns
2. **Enable ML classifier** - Set `AGENTGUARD_USE_ML=true`
3. **Enable LLM Judge** - Set `AGENTGUARD_USE_LLM_JUDGE=true` for ambiguous cases
4. **Enable Triple Judge** - Configure Prompt Guard + Llama Guard + DeepSeek

"""
    elif score < 85:
        md += """### 🟡 Improvements Needed

1. **Review missed attacks** - Add specific patterns for worst cases
2. **Tune thresholds** - Adjust confidence thresholds per category
3. **Add multilingual support** - Expand patterns for non-English attacks

"""
    else:
        md += """### 🟢 Excellent Performance

- Detection engine is performing well
- Continue monitoring with regular benchmark runs
- Consider adding new attack categories as they emerge

"""
    
    md += f"""
---

## 📈 Next Steps

1. Run benchmark regularly: `python benchmarks/benchmark.py`
2. Export to JSON: `python benchmarks/benchmark.py -o results.json`
3. Track score over time in CI/CD pipeline
4. Set minimum score threshold: **70/100**

---

*Generated by AgentGuard Adversarial Benchmark v1.0*
"""
    
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(md)
    
    print(f"📝 Markdown report saved to {output_path}")


